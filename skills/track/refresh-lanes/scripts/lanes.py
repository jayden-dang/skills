"""Render docs/roadmap/lanes.md — the parallel lanes derived from ## Focus — from a snapshot.

Generated, never hand-edited, and written only where it is committed: on the base branch
(`Default PR base:`), with a Focus, and when a lane line changed — a new tracker reading
alone does not rewrite it. Lanes, states and slots come from the snapshot (extract.py);
claims come from open tracker issues and are a reading taken at one moment, so the header
records when. Claiming work or taking a slot always re-reads the tracker and the lock live.

    gh issue list --state open --json number,title,assignees,labels,updatedAt,state --limit 500 > issues.json
    python3 lanes.py snapshot.json --issues issues.json --tracker-read <ISO time> --out docs/roadmap/lanes.md

Prints what happened: `written`, `unchanged`, `no Focus`, or `not on <base>`.
"""

from __future__ import annotations

import argparse
import datetime as dt
import json
import re
import sys
from pathlib import Path

STALE_DAYS = 7


def claims_from_issues(issues: list[dict]) -> dict[str, list[dict]]:
    """A claim is an open, assigned issue whose title names the ROAD; a mention in passing is not."""
    out: dict[str, list[dict]] = {}
    for i in issues:
        who = [a["login"] for a in i.get("assignees", [])]
        if not who or i.get("state", "OPEN") != "OPEN":
            continue
        title = re.sub(r"\(.*?\)", "", i["title"])
        for rid in dict.fromkeys(re.findall(r"ROAD-\d+", title)):
            out.setdefault(rid, []).append({"number": i["number"], "who": who, "updated": i.get("updatedAt", "")})
    return out


def render_lanes(snap: dict, claims: dict[str, list[dict]] | None, tracker_read: str | None) -> str:
    STATE = snap["labels"]
    items = {i["id"]: i for i in snap["items"]}
    names = {m["id"]: m["name"] for m in snap["milestones"]}
    ready = set(snap["graph"]["ready"])
    blocked = snap["graph"]["blocked"]
    today = dt.date.fromisoformat(snap["today"])
    integ = snap.get("integration", {})
    ref = integ.get("ref") or "HEAD"
    source = f"{snap['branch'] if ref == 'HEAD' else ref}@{(integ.get('sha') or snap['head'])[:9]}"
    lines = [
        "# Lanes",
        "",
        "Generated by the `refresh-lanes` skill from `## Focus` in `docs/roadmap/INDEX.md` — do not edit by hand.",
        f"Source: `{source}` · Tracker read: {tracker_read or 'not read — claims not shown'}",
        "Claims below are a reading at that time. Claiming an item or taking a slot re-reads the tracker and the lock.",
    ]

    def claimed(rid: str) -> str:
        if claims is None:
            return "—"
        cs = claims.get(rid, [])
        out = []
        for c in cs:
            mark = f"{' '.join('@' + w for w in c['who'])} #{c['number']}"
            if c["updated"] and (today - dt.date.fromisoformat(c["updated"][:10])).days >= STALE_DAYS:
                mark += " (stale)"
            out.append(mark)
        return ", ".join(out) or "unclaimed"

    def lane_block(n: int, lane: dict) -> list[str]:
        entry = lane["entry"]
        title = names.get(entry) or items[entry]["slug"]
        block = ["", f"### {n}. {entry} — {title}", ""]
        open_items = [r for r in lane["items"] if items[r]["state"] != "done"]
        if open_items:
            block += ["| ROAD | Item | State | Claimed by | Waiting on |", "|---|---|---|---|---|"]
            for r in open_items:
                state = STATE.get(items[r]["state"], items[r]["state"])
                if r in ready:  # a ready item that already has a spec is a different pick from one that has none
                    state = STATE["ready"] + (" · spec written" if items[r]["state"] == "specced" else "")
                block.append(f"| {r} | {items[r]['slug']} | {state} | {claimed(r)} | {', '.join(blocked.get(r, [])) or '—'} |")
        done = [r for r in lane["items"] if items[r]["state"] == "done"]
        if done:
            block += ["", f"Done: {', '.join(done)}"]
        return block

    lanes = snap.get("focus", {}).get("lanes", [])
    for horizon, heading in (("now", "Now"), ("next", "Next")):
        lines += ["", f"## {heading}"]
        mine = [l for l in lanes if l["horizon"] == horizon]
        if not mine:
            lines += ["", "None."]
        for n, lane in enumerate(mine, 1):
            lines += lane_block(n, lane)

    lines += ["", "## Slots", ""]
    slots = snap.get("slots", {})
    if not slots:
        lines.append("No serialized surfaces declared.")
    for surface, s in slots.items():
        waiting = ", ".join(w["item"] for w in s["waiting"]) or "none"
        lines.append(f"- `{surface}` — held by {s['holder'] or 'nobody'} (lock `{s['lock']}`) · waiting: {waiting}")

    lines += ["", "## Findings", ""]
    shown = [f for f in snap["findings"] if f["rule"] in ("S9", "F-OUT", "DELIVERY", "SLOT")]
    lines += [f"- {f['rule']} {f['item']}: {f['detail']}" for f in shown] or ["None."]
    return "\n".join(lines) + "\n"


def body(text: str) -> str:
    """Everything below the header: what a reader acts on. The header changes on every run."""
    return text.split("\n## ", 1)[1] if "\n## " in text else ""


def write_lanes(snap: dict, claims: dict[str, list[dict]] | None, tracker_read: str | None, out: Path) -> str:
    base = snap.get("integration", {}).get("base")
    if not snap.get("focus", {}).get("present"):
        return "no Focus"
    if base and snap["branch"] != base:
        return f"not on {base}"
    text = render_lanes(snap, claims, tracker_read)
    if out.exists() and body(out.read_text()) == body(text):
        return "unchanged"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text)
    return "written"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("snapshot")
    ap.add_argument("--issues", help="JSON from `gh issue list --json number,title,assignees,labels,updatedAt,state`")
    ap.add_argument("--tracker-read", help="ISO time the issues were read")
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    snap = json.loads(Path(a.snapshot).read_text())
    claims = claims_from_issues(json.loads(Path(a.issues).read_text())) if a.issues else None
    print(write_lanes(snap, claims, a.tracker_read if a.issues else None, Path(a.out)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
